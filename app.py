
import streamlit as st
import pandas as pd
import numpy as np
import joblib
import matplotlib.pyplot as plt

from pathlib import Path
from sklearn.metrics import (
    accuracy_score,
    roc_auc_score,
    precision_score,
    recall_score,
    f1_score,
    matthews_corrcoef,
    confusion_matrix,
    ConfusionMatrixDisplay,
    classification_report
)

# =====================================================
# 1. PAGE CONFIGURATION
# =====================================================

st.set_page_config(
    page_title="Dry Bean Classification",
    page_icon="🌱",
    layout="wide"
)

BASE_DIR = Path(__file__).resolve().parent
MODEL_DIR = BASE_DIR / "model"

# =====================================================
# 2. DATASET FEATURES
# =====================================================

FEATURE_COLUMNS = [
    "Area",
    "Perimeter",
    "MajorAxisLength",
    "MinorAxisLength",
    "AspectRation",
    "Eccentricity",
    "ConvexArea",
    "EquivDiameter",
    "Extent",
    "Solidity",
    "roundness",
    "Compactness",
    "ShapeFactor1",
    "ShapeFactor2",
    "ShapeFactor3",
    "ShapeFactor4"
]

TARGET_COLUMN = "Class"

# =====================================================
# 3. MODEL FILES
# =====================================================

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "knn.joblib",
    "Gaussian Naive Bayes": "naive_bayes.joblib",
    "Support Vector Machine": "svm.joblib"
}

# =====================================================
# 4. APPLICATION HEADER
# =====================================================

st.title("🌱 Dry Bean Classification System")

st.write(
    """
    This interactive Machine Learning application
    classifies dry bean varieties using five different
    classification algorithms.

    Upload your test dataset, select a trained model,
    and evaluate its classification performance.
    """
)

st.divider()

# =====================================================
# 5. CHECK TRAINED MODEL FILES
# =====================================================

encoder_path = MODEL_DIR / "label_encoder.joblib"

missing_files = []

if not encoder_path.exists():
    missing_files.append("label_encoder.joblib")

for filename in MODEL_FILES.values():

    if not (MODEL_DIR / filename).exists():
        missing_files.append(filename)

if missing_files:

    st.error("Some trained model files are missing.")

    st.write("Missing files:")

    for filename in missing_files:
        st.write("- " + filename)

    st.warning(
        "Please run python train.py from your project folder "
        "before starting this application."
    )

    st.stop()

# =====================================================
# 6. LOAD LABEL ENCODER
# =====================================================

try:

    encoder = joblib.load(encoder_path)

    class_names = encoder.classes_.tolist()

except Exception as error:

    st.error("Unable to load the label encoder.")
    st.code(str(error))
    st.stop()

# =====================================================
# 7. MODEL SELECTION
# =====================================================

st.subheader("Select Classification Model")

selected_model = st.selectbox(
    "Choose a machine learning algorithm:",
    list(MODEL_FILES.keys())
)

st.write("Selected model:", selected_model)

# =====================================================
# 8. TEST DATA UPLOAD
# =====================================================

st.divider()

st.subheader("Upload Test Dataset")

st.write(
    "Upload the test_data.csv file generated by train.py. "
    "The CSV must contain 16 input features and the Class column."
)

uploaded_file = st.file_uploader(
    "Choose your test CSV file",
    type=["csv"]
)

# =====================================================
# 9. PROCESS UPLOADED DATASET
# =====================================================

if uploaded_file is not None:

    try:

        # Read uploaded CSV
        data = pd.read_csv(uploaded_file)

        # Clean column names
        data.columns = (
            data.columns.astype(str)
            .str.replace("\ufeff", "", regex=False)
            .str.strip()
        )

        # Normalize Class column capitalization
        for column in data.columns:

            if column.lower() == "class":
                data.rename(
                    columns={column: TARGET_COLUMN},
                    inplace=True
                )
                break

        # Check empty dataset
        if data.empty:

            st.error("The uploaded CSV file is empty.")
            st.stop()

        # Required columns
        required_columns = FEATURE_COLUMNS + [TARGET_COLUMN]

        missing_columns = [
            column for column in required_columns
            if column not in data.columns
        ]

        if missing_columns:

            st.error("Required columns are missing.")

            st.write("Missing columns:", missing_columns)

            st.write("Available columns:", data.columns.tolist())

            st.stop()

        # Select input features
        X_test = data[FEATURE_COLUMNS].copy()

        # Convert features to numeric values
        X_test = X_test.apply(
            pd.to_numeric,
            errors="coerce"
        )

        if X_test.isnull().any().any():

            st.error(
                "Some input features contain missing or "
                "non-numeric values. Please correct the CSV."
            )

            st.stop()

        # Actual target values
        y_original = (
            data[TARGET_COLUMN]
            .astype(str)
            .str.strip()
        )

        if y_original.eq("").any():

            st.error("The Class column contains empty values.")
            st.stop()

        # Check for unknown classes
        unknown_classes = sorted(
            set(y_original) - set(class_names)
        )

        if unknown_classes:

            st.error(
                "Unknown bean classes found in uploaded data."
            )

            st.write("Unknown classes:", unknown_classes)

            st.stop()

        # Encode actual class values
        y_true = encoder.transform(y_original)

        st.success("Test dataset uploaded successfully!")

        # =================================================
        # 10. DATASET INFORMATION
        # =================================================

        st.subheader("Uploaded Dataset Information")

        col1, col2, col3 = st.columns(3)

        col1.metric("Total Instances", len(data))

        col2.metric("Input Features", len(FEATURE_COLUMNS))

        col3.metric("Bean Classes", y_original.nunique())

        with st.expander("Preview uploaded dataset"):

            st.dataframe(
                data.head(10),
                use_container_width=True
            )

        # =================================================
        # 11. LOAD SELECTED MODEL
        # =================================================

        model_path = MODEL_DIR / MODEL_FILES[selected_model]

        model = joblib.load(model_path)

        # Check model class compatibility
        if not np.array_equal(
            model.classes_,
            np.arange(len(class_names))
        ):

            st.error(
                "The saved model classes do not match "
                "the saved label encoder."
            )

            st.stop()

        # =================================================
        # 12. PREDICTIONS
        # =================================================

        predictions = model.predict(X_test)

        probabilities = model.predict_proba(X_test)

        # Convert predicted numerical labels
        # into original bean variety names
        predicted_names = encoder.inverse_transform(
            predictions.astype(int)
        )

        # =================================================
        # 13. EVALUATION METRICS
        # =================================================

        accuracy = accuracy_score(
            y_true,
            predictions
        )

        auc = roc_auc_score(
            y_true,
            probabilities,
            multi_class="ovr",
            average="weighted",
            labels=np.arange(len(class_names))
        )

        precision = precision_score(
            y_true,
            predictions,
            average="weighted",
            zero_division=0
        )

        recall = recall_score(
            y_true,
            predictions,
            average="weighted",
            zero_division=0
        )

        f1 = f1_score(
            y_true,
            predictions,
            average="weighted",
            zero_division=0
        )

        mcc = matthews_corrcoef(
            y_true,
            predictions
        )

        # =================================================
        # 14. DISPLAY EVALUATION RESULTS
        # =================================================

        st.divider()

        st.subheader("Model Evaluation Results")

        st.write("Selected algorithm:", selected_model)

        st.caption(
            "Metrics are calculated using the uploaded "
            "labelled test dataset."
        )

        col1, col2, col3 = st.columns(3)

        col1.metric("Accuracy", f"{accuracy:.4f}")

        col2.metric("AUC Score", f"{auc:.4f}")

        col3.metric("Precision", f"{precision:.4f}")

        col4, col5, col6 = st.columns(3)

        col4.metric("Recall", f"{recall:.4f}")

        col5.metric("F1 Score", f"{f1:.4f}")

        col6.metric("MCC Score", f"{mcc:.4f}")

        # =================================================
        # 15. CONFUSION MATRIX
        # =================================================

        st.divider()

        st.subheader("Confusion Matrix")

        cm = confusion_matrix(
            y_true,
            predictions,
            labels=np.arange(len(class_names))
        )

        fig, ax = plt.subplots(figsize=(11, 8))

        display = ConfusionMatrixDisplay(
            confusion_matrix=cm,
            display_labels=class_names
        )

        display.plot(
            ax=ax,
            cmap="Blues",
            xticks_rotation=45,
            colorbar=False
        )

        ax.set_title(selected_model + " Confusion Matrix")

        plt.tight_layout()

        st.pyplot(fig)

        plt.close(fig)

        # =================================================
        # 16. CLASSIFICATION REPORT
        # =================================================

        st.subheader("Classification Report")

        report = classification_report(
            y_true,
            predictions,
            labels=np.arange(len(class_names)),
            target_names=class_names,
            output_dict=True,
            zero_division=0
        )

        report_df = pd.DataFrame(report).transpose()

        st.dataframe(
            report_df.round(4),
            use_container_width=True
        )

        # =================================================
        # 17. PREDICTION RESULTS
        # =================================================

        st.divider()

        st.subheader("Prediction Results")

        output_data = data.copy()

        output_data["Predicted Class"] = predicted_names

        output_data["Prediction Status"] = np.where(
            y_original.to_numpy() == predicted_names,
            "Correct",
            "Incorrect"
        )

        st.dataframe(
            output_data.head(20),
            use_container_width=True
        )

        # Download results
        csv_output = output_data.to_csv(index=False).encode("utf-8")

        st.download_button(
            label="Download Prediction Results",
            data=csv_output,
            file_name="dry_bean_prediction_results.csv",
            mime="text/csv"
        )

        # =================================================
        # 18. SUCCESS MESSAGE
        # =================================================

        st.success(
            "Evaluation completed successfully!"
        )

    except Exception as error:

        st.error("An error occurred during evaluation.")

        st.code(str(error))


